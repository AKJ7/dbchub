#!/usr/bin/env python3
"""Convert a database into other formats for download.

Every file in the catalog is offered as:
  * DBC  — normalized by canmatrix (e.g. 29-bit ids get the extended flag), so
           KCD/SYM sources become DBC and quirky DBCs become tool-friendly
  * KCD  — Kayak XML
  * SYM  — PCAN Symbol Editor
  * CSV  — one row per signal, for spreadsheets
  * ARXML (zip) — AUTOSAR 4 system description
  * C (zip) — cantools-generated pack/unpack code (header + source)
The source format itself is skipped (the original file is already downloadable).
Exports are best effort: a format that fails for a file is simply left out.
"""
from __future__ import annotations

import io
import logging
import re
import tempfile
import zipfile
from pathlib import Path

# (format id, label, file suffix, zipped)
FORMATS = [
    ("dbc", "DBC (normalized)", ".dbc", False),
    ("kcd", "KCD (Kayak)", ".kcd", False),
    ("sym", "SYM (PCAN)", ".sym", False),
    ("csv", "CSV (signals)", ".csv", False),
    ("arxml", "ARXML (AUTOSAR)", ".arxml.zip", True),
    ("c", "C code (cantools)", ".c.zip", True),
]


def _c_identifier(stem: str) -> str:
    name = re.sub(r"[^0-9a-zA-Z_]", "_", stem).lower()
    return name if name and not name[0].isdigit() else "db_" + name


def export_all(matrices, src_ext: str, out_dir: Path, stem: str) -> list[dict]:
    """Write exports of `matrices` into out_dir. Returns [{format, label, file}]."""
    import canmatrix.formats

    out_dir.mkdir(parents=True, exist_ok=True)
    done: list[dict] = []
    logging.disable(logging.WARNING)  # canmatrix is chatty about attributes it drops
    try:
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            dbc_text = None
            for fmt, label, suffix, zipped in FORMATS:
                if fmt == src_ext.lstrip(".") and fmt != "dbc":
                    continue
                target = out_dir / f"{stem}{suffix}"
                try:
                    if fmt == "c":
                        payload = _c_zip(dbc_text, stem) if dbc_text else None
                        if payload is None:
                            continue
                        target.write_bytes(payload)
                    else:
                        raw = tmp / f"{stem}.{fmt}"
                        canmatrix.formats.dumpp(matrices, str(raw))
                        if fmt == "dbc":
                            dbc_text = raw.read_text(encoding="iso-8859-1")
                        if zipped:
                            with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
                                z.write(raw, raw.name)
                        else:
                            target.write_bytes(raw.read_bytes())
                    done.append({"format": fmt, "label": label, "file": target.name})
                except Exception:  # noqa: BLE001 - best effort per format
                    target.unlink(missing_ok=True)
    finally:
        logging.disable(logging.NOTSET)
    return done


def _c_zip(dbc_text: str, stem: str) -> bytes | None:
    import cantools
    from cantools.database.can.c_source import generate

    db = cantools.database.load_string(dbc_text, "dbc", strict=False)
    if not db.messages:
        return None
    name = _c_identifier(stem)
    header, source, *_ = generate(db, name, f"{name}.h", f"{name}.c", f"{name}_fuzzer.c")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{name}.h", header)
        z.writestr(f"{name}.c", source)
        z.writestr("README.txt",
                   f"Generated by cantools from {stem} (via a canmatrix-normalized DBC).\n"
                   "Reverse-engineered data: not validated for safety-critical use.\n")
    return buf.getvalue()
