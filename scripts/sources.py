#!/usr/bin/env python3
"""Keep imported databases in sync with their upstream sources.

The manifest is databases/SOURCES.json. Each source pins a git `commit` and lists
its `files` (`path` under databases/, `upstream` path in the source repo, optional
`method`). Commands:

  check                 report sources whose upstream has moved past the pinned commit
  sync [--source NAME]  re-import files at the pinned commit (verifies the copies)
       [--to latest|SHA] ... or move the pin, re-import, and report what changed
       [--dry-run]       show what would change without writing
  attributions          regenerate the per-source tables in ATTRIBUTIONS.md

Upstream repositories are untrusted input: they are fetched into a temporary
directory and files are only copied (or, for `opendbc-generator`, concatenated
exactly like opendbc's generator.py does). No upstream code is ever executed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DB_ROOT = REPO / "databases"
MANIFEST = DB_ROOT / "SOURCES.json"
ATTRIBUTIONS = REPO / "ATTRIBUTIONS.md"
BEGIN, END = "<!-- BEGIN SOURCES (generated by scripts/sources.py attributions) -->", "<!-- END SOURCES -->"
SHA = re.compile(r"^[0-9a-f]{7,40}$")


def load() -> dict:
    return json.loads(MANIFEST.read_text())


def save(data: dict) -> None:
    MANIFEST.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def git(*args, cwd=None) -> str:
    return subprocess.check_output(["git", *args], cwd=cwd, text=True, stderr=subprocess.PIPE).strip()


def remote_head(url: str) -> str | None:
    try:
        out = git("ls-remote", url, "HEAD")
    except subprocess.CalledProcessError:
        return None
    return out.split()[0] if out else None


def fetch(url: str, commit: str, into: Path) -> None:
    """Shallow-fetch exactly one commit into an empty directory."""
    git("init", "-q", cwd=into)
    git("remote", "add", "origin", url, cwd=into)
    git("fetch", "-q", "--depth", "1", "origin", commit, cwd=into)
    git("checkout", "-q", "FETCH_HEAD", cwd=into)


_INCLUDE = re.compile(r'CM_ "IMPORT (.*?)";\n')


def opendbc_generate(template: Path) -> bytes:
    """Re-implementation of opendbc/dbc/generator/generator.py's concatenation."""
    text = template.read_text(encoding="utf-8")
    parts = ['CM_ "AUTOGENERATED FILE, DO NOT EDIT";\n']
    for inc in _INCLUDE.findall(text):
        inc_path = (template.parent / inc).resolve()
        if template.parent.resolve() not in inc_path.parents:
            raise ValueError(f"IMPORT escapes the template directory: {inc}")
        parts.append(f'\n\nCM_ "Imported file {inc} starts here";\n')
        parts.append(inc_path.read_text(encoding="utf-8"))
    parts.append(f'\nCM_ "{template.name} starts here";\n')
    parts.append(_INCLUDE.sub("", text))
    return "".join(parts).encode("utf-8")


def produce(checkout: Path, entry: dict) -> bytes:
    src = (checkout / entry["upstream"]).resolve()
    if checkout.resolve() not in src.parents:
        raise ValueError(f"upstream path escapes the checkout: {entry['upstream']}")
    method = entry.get("method", "copy")
    if method == "copy":
        return src.read_bytes()
    if method == "opendbc-generator":
        return opendbc_generate(src)
    raise ValueError(f"unknown method {method!r}")


def _digest(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()[:12]


def cmd_check(args) -> int:
    data = load()
    behind = 0
    for s in data["sources"]:
        if args.source and s["name"] != args.source:
            continue
        head = remote_head(s["url"])
        pinned = s.get("commit", "")
        if head is None:
            state = "unreachable"
        elif head.startswith(pinned) or pinned.startswith(head):
            state = "up to date"
        else:
            state = f"upstream moved: {pinned[:12]} -> {head[:12]}"
            behind += 1
        print(f"{s['name']:<50} {state}")
    print(f"\n{behind} source(s) have upstream changes. Run `scripts/sources.py sync --to latest` to update.")
    return 0


def cmd_sync(args) -> int:
    data = load()
    changed_any = False
    for s in data["sources"]:
        if args.source and s["name"] != args.source:
            continue
        target = s["commit"]
        if args.to == "latest":
            target = remote_head(s["url"]) or target
        elif args.to:
            if not SHA.match(args.to):
                sys.exit("--to must be 'latest' or a commit sha")
            target = args.to
        print(f"== {s['name']} @ {target[:12]}")
        with tempfile.TemporaryDirectory() as tmp:
            checkout = Path(tmp) / "src"
            checkout.mkdir()
            try:
                fetch(s["url"], target, checkout)
            except subprocess.CalledProcessError as exc:
                print(f"   ! could not fetch: {exc.stderr.strip()[:200]}")
                continue
            for entry in s["files"]:
                dest = DB_ROOT / entry["path"]
                try:
                    new = produce(checkout, entry)
                except FileNotFoundError:
                    print(f"   ! missing upstream: {entry['upstream']} (kept {entry['path']})")
                    continue
                except ValueError as exc:
                    print(f"   ! {entry['path']}: {exc}")
                    continue
                old = dest.read_bytes() if dest.exists() else None
                if old == new:
                    continue
                changed_any = True
                print(f"   {'updated' if old is not None else 'added'}: {entry['path']} "
                      f"({_digest(old) if old else '-'} -> {_digest(new)})")
                if not args.dry_run:
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    dest.write_bytes(new)
            lic_up, lic_file = s.get("license_upstream"), s.get("license_file")
            if lic_up and lic_file and (checkout / lic_up).is_file():
                new_lic = (checkout / lic_up).read_bytes()
                if (REPO / lic_file).read_bytes() != new_lic:
                    changed_any = True
                    print(f"   license text changed: {lic_file} — review before merging!")
                    if not args.dry_run:
                        (REPO / lic_file).write_bytes(new_lic)
        if target != s["commit"] and not args.dry_run:
            s["commit"] = target
            changed_any = True
    if not args.dry_run:
        save(data)
    print("\nChanges written." if changed_any and not args.dry_run else "\nNo changes." if not changed_any else "\n(dry run)")
    return 0


def cmd_attributions(args) -> int:
    data = load()
    out = [BEGIN, ""]
    for s in data["sources"]:
        out.append(f"## {s['name']}\n")
        out.append(f"- **Source:** {s['url']}")
        out.append(f"- **License:** {s['license']} — full text in [`{s['license_file']}`]({s['license_file']})")
        out.append(f"- **Credit:** {s['attribution']}")
        out.append(f"- **Imported at commit:** `{s['commit']}`")
        for n in s.get("notices", []):
            out.append(f"- **Additional notice:** [`{n}`]({n})")
        out.append("")
        out.append("| Path | Upstream |")
        out.append("|---|---|")
        for f in s["files"]:
            how = " (assembled by opendbc's generator)" if f.get("method") == "opendbc-generator" else ""
            out.append(f"| `databases/{f['path']}` | `{f['upstream']}`{how} |")
        out.append("")
    out.append(END)
    block = "\n".join(out)
    text = ATTRIBUTIONS.read_text()
    if BEGIN in text and END in text:
        text = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        raise SystemExit(f"{ATTRIBUTIONS} has no {BEGIN} … {END} block")
    ATTRIBUTIONS.write_text(text)
    print(f"Updated {ATTRIBUTIONS.relative_to(REPO)}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check", help="report upstream changes")
    c.add_argument("--source")
    s = sub.add_parser("sync", help="re-import files")
    s.add_argument("--source")
    s.add_argument("--to", help="'latest' or a commit sha (default: the pinned commit)")
    s.add_argument("--dry-run", action="store_true")
    sub.add_parser("attributions", help="regenerate ATTRIBUTIONS.md tables")
    args = ap.parse_args()
    return {"check": cmd_check, "sync": cmd_sync, "attributions": cmd_attributions}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
